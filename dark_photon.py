"""
Limits on the kinetic mixing epsilon of a dark photon, digitized from published figures, for a
dark photon that decays mostly INVISIBLY (into the dark sector), plus a few related curves.

Each array has columns (dark photon mass in GeV, largest allowed epsilon); values above the
curve are excluded. The curves were traced pixel by pixel from the figures, so they are good to
roughly 2-5% in epsilon and 1% in mass. Use the original papers for anything precise.

Conventions: epsilon is as plotted in each source, except that Harigaya et al. plot
eta = (eps / c_W) / sqrt(1 - eps^2 / c_W^2), converted here with c_W = 0.881, and the CMS
review plots epsilon^2 against the dark matter mass (converted, see CMS_MONOJET).

What is in here:
  LIMITS                   limits assuming the dark photon decays invisibly (branching ratio ~ 1)
                           and not depending on the dark coupling; epsilon_max() uses these
  DILEPTON_BY_ALPHA_D      dilepton searches for a dark photon that also decays invisibly, for
                           alpha_D = 1e-1 ... 1e-4 and m_chi = m / 3
  LHC_DILEPTON_BY_WIDTH    LHC dilepton bounds above the Z for invisible widths of 0.5, 1, 2 %
  Z_INVISIBLE_BY_WIDTH     bounds from the Z invisible width, same widths
  DILEPTON_NO_DARK_DECAYS  dilepton bound when the dark photon cannot decay into the dark
                           sector (m_D < 2 M_CHI in your model)
  HL_LHC_MONOJET           projected HL-LHC monojet sensitivity (not a limit)
"""

