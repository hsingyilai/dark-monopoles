def epsilon_max(mass, limits=LIMITS):
    """Strongest limit on epsilon at the given dark photon mass(es) in GeV: the smallest
    value among the curves that cover that mass, interpolated in log-log. NaN if none do."""
    mass = np.atleast_1d(np.asarray(mass, dtype=float))
    best = np.full(mass.shape, np.inf)
    for curve in limits.values():
        log_m, log_eps = np.log10(curve[:, 0]), np.log10(curve[:, 1])
        inside = (mass >= curve[0, 0]) & (mass <= curve[-1, 0])
        values = 10 ** np.interp(np.log10(mass[inside]), log_m, log_eps)
        best[inside] = np.minimum(best[inside], values)
    best[np.isinf(best)] = np.nan
    return best


